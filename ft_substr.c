#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*res;
	size_t	slen;

	if (!s)
		return (NULL);
	slen = ft_strlen(s);
	if (start >= slen)
		return (ft_strdup(""));
	if (len > slen - start)
		len = slen - start;
	res = malloc((len + 1) * sizeof(char));
	if (!res)
	{
		return (NULL);
	}
	ft_strlcpy(res, s + start, len + 1);
	return (res);
}
