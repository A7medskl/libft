#include "libft.h"

void	*ft_memchr(const void *b, int c, size_t n)
{
	unsigned char	*p;
	size_t			i;

	if (!b)
		return (NULL);
	i = 0;
	p = (unsigned char *)b;
	while (i < n)
	{
		if (p[i] == (unsigned char)c)
		{
			return (p + i);
		}
		i++;
	}
	return (NULL);
}
